CREATE TABLE surf_spots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    country VARCHAR(80) NOT NULL,
    region VARCHAR(120) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    difficulty VARCHAR(30) NOT NULL,
    best_wind_direction VARCHAR(40),
    best_swell_direction VARCHAR(40),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_surf_spots_name_region_country UNIQUE (name, region, country),
    CONSTRAINT ck_surf_spots_latitude CHECK (latitude >= -90 AND latitude <= 90),
    CONSTRAINT ck_surf_spots_longitude CHECK (longitude >= -180 AND longitude <= 180),
    CONSTRAINT ck_surf_spots_difficulty CHECK (difficulty IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT'))
);

CREATE TABLE ski_resorts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    country VARCHAR(80) NOT NULL,
    region VARCHAR(120) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    base_altitude INTEGER NOT NULL,
    top_altitude INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_ski_resorts_name_region_country UNIQUE (name, region, country),
    CONSTRAINT ck_ski_resorts_latitude CHECK (latitude >= -90 AND latitude <= 90),
    CONSTRAINT ck_ski_resorts_longitude CHECK (longitude >= -180 AND longitude <= 180),
    CONSTRAINT ck_ski_resorts_base_altitude CHECK (base_altitude > 0),
    CONSTRAINT ck_ski_resorts_top_altitude CHECK (top_altitude > 0),
    CONSTRAINT ck_ski_resorts_altitude_range CHECK (top_altitude >= base_altitude)
);
